"""apps-api's request models against the App CRD they mirror.

The CRD (generated by controller-gen from operator/api/) is the source of
truth for an App's shape. The models are hand-written because they also carry
request rules the CRD does not (git URL checks, extra="forbid" on request
bodies, PATCH semantics); this test fails when they drift from it, as the UI's
types do through .github/scripts/gen_crd_types.py.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, get_args

import pytest
import yaml
from pydantic import BaseModel

from nebari_apps_api import models

CRD = Path(__file__).resolve().parents[2] / "charts/nebari-apps/crds/apps.nebari.dev_apps.yaml"


@pytest.fixture(scope="module")
def spec() -> dict[str, Any]:
    crd = yaml.safe_load(CRD.read_text())
    version = next(v for v in crd["spec"]["versions"] if v.get("storage"))
    return version["schema"]["openAPIV3Schema"]["properties"]["spec"]


def at(schema: dict[str, Any], path: str) -> dict[str, Any]:
    for part in path.split("."):
        schema = schema["items"] if part == "[]" else schema["properties"][part]
    return schema


# model -> (CRD path under spec, CRD fields it leaves out on purpose, fields it adds)
MIRRORS: dict[type[BaseModel], tuple[str, set[str], set[str]]] = {
    models.GitSource: ("source.git", set(), set()),
    models.InlineSource: ("source.inline", set(), set()),
    models.PVCSource: ("source.pvc", set(), set()),
    models.AppSource: ("source", set(), set()),
    models.EnvVar: ("runtime.env.[]", set(), set()),
    # claims (DRA) are kept by extra="allow", not modeled.
    models.Resources: ("runtime.resources", {"claims"}, set()),
    models.AppRuntime: ("runtime", set(), set()),
    models.AppAccess: ("access", set(), set()),
    models.AppLandingPage: ("landingPage", set(), set()),
    # owner is set by the API from the caller; name and namespace are metadata.
    models.AppCreate: ("", {"owner"}, {"name", "namespace"}),
    models.AppPatch: ("", {"owner"}, set()),
}


@pytest.mark.parametrize("model", list(MIRRORS), ids=lambda m: m.__name__)
def test_model_fields_match_the_crd(spec, model):
    path, left_out, added = MIRRORS[model]
    schema = at(spec, path) if path else spec
    crd_fields = set(schema["properties"])
    model_fields = set(model.model_fields)
    missing = crd_fields - left_out - model_fields
    unknown = model_fields - added - crd_fields
    assert not missing, f"{model.__name__} lacks CRD field(s) {sorted(missing)} at spec.{path}"
    assert not unknown, f"{model.__name__} has field(s) {sorted(unknown)} that spec.{path} does not"


def test_source_types_match_the_crd_enum(spec):
    assert set(get_args(models.SourceType)) == set(at(spec, "source.type")["enum"])


def test_request_bounds_match_the_crd(spec):
    """The API rejects what the CRD would, with a 422 instead of a 500 from the apiserver."""

    def constraint(model: type[BaseModel], field: str, name: str) -> Any:
        for meta in model.model_fields[field].metadata:
            if hasattr(meta, name):
                return getattr(meta, name)
        return None

    replicas = at(spec, "runtime.replicas")
    assert constraint(models.AppRuntime, "replicas", "ge") == replicas["minimum"]
    assert constraint(models.AppRuntime, "replicas", "le") == replicas["maximum"]
    subdomain = at(spec, "access.subdomain")
    assert constraint(models.AppAccess, "subdomain", "max_length") == subdomain["maxLength"]
    assert constraint(models.AppAccess, "subdomain", "pattern") == subdomain["pattern"]
    assert constraint(models.AppRuntime, "pixiTask", "max_length") == at(spec, "runtime.pixiTask")["maxLength"]
    idle = at(spec, "runtime.idleTimeoutMinutes")
    assert constraint(models.AppRuntime, "idleTimeoutMinutes", "ge") == idle["minimum"]
    assert constraint(models.AppRuntime, "idleTimeoutMinutes", "le") == idle["maximum"]


def test_status_phases_match_the_crd_enum():
    crd = yaml.safe_load(CRD.read_text())
    version = next(v for v in crd["spec"]["versions"] if v.get("storage"))
    phases = version["schema"]["openAPIV3Schema"]["properties"]["status"]["properties"]["phase"]["enum"]
    assert "Idle" in phases
    assert set(models.AppStatus.model_fields) >= {"phase", "lastActivityTime"}
